"""Create a synthetic `yolo_e2e` model directory for GPU smoke tests (no user weights needed).

The ONNX graph ignores the image content and outputs fixed detections [batch, K, 6]
(x1, y1, x2, y2, score, class in 640x640 network pixels), so the whole path
nvinfer -> libperceptra_parsers.so -> tracker -> probe can be exercised end to end.
The model, its labels and model.yaml are our own (Apache-2.0). Usage::

    python3 tests/integration/make_synthetic_onnx.py /opt/perceptra/models/synthetic-e2e
    python3 tests/integration/make_synthetic_onnx.py --variant b \\
        /opt/perceptra/models/synthetic-e2e-b
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import onnx
from onnx import TensorProto, helper

DETECTIONS = [
    # x1, y1, x2, y2, score, class
    [100.0, 120.0, 220.0, 420.0, 0.90, 0],  # person
    [300.0, 150.0, 380.0, 330.0, 0.80, 0],  # person
    [400.0, 400.0, 600.0, 560.0, 0.85, 1],  # car: dropped by classes.keep
    [50.0, 50.0, 90.0, 90.0, 0.10, 0],  # below threshold
]
# Variant "b" adds a third person: used to verify a model hot swap is visible in the events.
EXTRA_PERSON_B = [480.0, 100.0, 560.0, 300.0, 0.95, 0]
LABELS = ["person", "car"]
MODEL_YAML = """\
# SPDX-License-Identifier: Apache-2.0
# Synthetic yolo_e2e model generated by tests/integration/make_synthetic_onnx.py.
schema_version: 1
name: @NAME@
version: "@VERSION@"
task: detect
license: { spdx: Apache-2.0, notes: "Synthetic test model (no weights)." }
files: { onnx: model.onnx, labels: labels.txt }
input: { width: 640, height: 640, resize: letterbox_center }
output: { family: yolo_e2e, layers: [output0], num_classes: 2 }
classes: { keep: [person], thresholds: { default: 0.35 } }
precision: fp16
"""


def build(variant: str = "a") -> onnx.ModelProto:
    rows = DETECTIONS + ([EXTRA_PERSON_B] if variant == "b" else [])
    k = len(rows)
    dets = np.array(rows, dtype=np.float32).reshape(1, k, 6)
    nodes = [
        helper.make_node("Shape", ["images"], ["in_shape"]),
        helper.make_node("Slice", ["in_shape", "zero", "one"], ["batch"]),
        helper.make_node("Concat", ["batch", "tail"], ["out_shape"], axis=0),
        helper.make_node("Expand", ["dets", "out_shape"], ["output0"]),
    ]
    inits = [
        helper.make_tensor("zero", TensorProto.INT64, [1], [0]),
        helper.make_tensor("one", TensorProto.INT64, [1], [1]),
        helper.make_tensor("tail", TensorProto.INT64, [2], [k, 6]),
        helper.make_tensor("dets", TensorProto.FLOAT, dets.shape, dets.flatten().tolist()),
    ]
    graph = helper.make_graph(
        nodes,
        "synthetic_e2e",
        [helper.make_tensor_value_info("images", TensorProto.FLOAT, ["batch", 3, 640, 640])],
        [helper.make_tensor_value_info("output0", TensorProto.FLOAT, ["batch", k, 6])],
        initializer=inits,
    )
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 17)])
    model.ir_version = 8
    onnx.checker.check_model(model)
    return model


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("out_dir", type=Path)
    ap.add_argument(
        "--variant",
        choices=["a", "b"],
        default="a",
        help="a: 2 persons kept per frame; b: 3 persons (same input/output shape)",
    )
    args = ap.parse_args()
    out = args.out_dir
    out.mkdir(parents=True, exist_ok=True)
    onnx.save(build(args.variant), str(out / "model.onnx"))
    (out / "labels.txt").write_text("\n".join(LABELS) + "\n")
    name = "synthetic-e2e" if args.variant == "a" else "synthetic-e2e-b"
    (out / "model.yaml").write_text(
        MODEL_YAML.replace("@NAME@", name).replace("@VERSION@", args.variant)
    )
    print(f"wrote {out}/model.onnx, labels.txt, model.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
